def picture(name, alt, sizes, eager=False, caption=None):
    widths = sorted(DIMS[name])
    largest = widths[-1]
    srcset = ", ".join(f"{IMG}{name}-{w}.webp {w}w" for w in widths)
    loading = 'fetchpriority="high"' if eager else 'loading="lazy"'
    img = (
        f'<img src="{IMG}{name}-{largest}.webp" srcset="{srcset}" sizes="{sizes}" '
        f'width="{largest}" height="{DIMS[name][largest]}" alt="{escape(alt)}" {loading} decoding="async">'
    )
    cap = f"<figcaption>{caption}</figcaption>" if caption else ""
    return f'<figure class="shot">{img}{cap}</figure>'


